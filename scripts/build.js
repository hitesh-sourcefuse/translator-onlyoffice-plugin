import {
    cpSync,
    existsSync,
    mkdirSync,
    readdirSync,
    readFileSync,
    rmSync,
    unlinkSync,
    writeFileSync,
} from "node:fs";
import { resolve } from "node:path";
import { build } from "vite";

const root = resolve(import.meta.dirname, "..");
const distDir = resolve(root, "dist");

// Entry points: name → source JS
const entries = {
    background: "src/background/main.js",
    panel: "src/panel/main.js",
    settings: "src/settings/main.js",
    sync: "src/sync/main.js",
    "translation-view": "src/translation-view/main.js",
};

// --- Step 1: Clean dist/ ---
if (existsSync(distDir)) {
    rmSync(distDir, { recursive: true });
}
mkdirSync(distDir, { recursive: true });
mkdirSync(resolve(distDir, "scripts"), { recursive: true });
mkdirSync(resolve(distDir, "styles"), { recursive: true });

// --- Step 2: Copy static/ → dist/ ---
cpSync(resolve(root, "static"), distDir, { recursive: true });
console.log("✓ Copied static assets");

// --- Step 2b: Copy vendor/bergamot → dist/vendor/bergamot ---
const bergamotSrc = resolve(root, "vendors/bergamot-translator");
const bergamotDst = resolve(distDir, "vendor/bergamot");
mkdirSync(bergamotDst, { recursive: true });
for (const file of ["translator.js", "translator.d.ts"]) {
    cpSync(resolve(bergamotSrc, file), resolve(bergamotDst, file));
}
cpSync(resolve(bergamotSrc, "worker"), resolve(bergamotDst, "worker"), {
    recursive: true,
});
console.log("✓ Copied bergamot-translator vendor");

// --- Step 3: Copy HTML files to dist root (flat, renamed) ---
for (const name of Object.keys(entries)) {
    const srcHtml = resolve(root, `src/${name}/index.html`);
    if (existsSync(srcHtml)) {
        cpSync(srcHtml, resolve(distDir, `${name}.html`));
    }
}

// Copy about
const aboutSrc = resolve(root, "src/about/index.html");
cpSync(aboutSrc, resolve(distDir, "index_about.html"));
console.log("✓ Copied HTML files (flat)");

// --- Step 4: Build each entry as IIFE → dist/scripts/{name}.js ---
// Collect CSS from each entry to merge later
const collectedCss = [];

for (const [name, entry] of Object.entries(entries)) {
    await build({
        configFile: false,
        logLevel: "warn",
        build: {
            lib: {
                entry: resolve(root, entry),
                formats: ["iife"],
                name: `Plugin_${name.replace(/-/g, "_")}`,
                fileName: () => `${name}.js`,
            },
            outDir: resolve(distDir, "scripts"),
            emptyOutDir: false,
            cssCodeSplit: false,
            minify: true,
            rollupOptions: {
                output: {
                    assetFileNames: `[name].[ext]`,
                },
            },
        },
    });

    // Collect any CSS generated by this entry
    for (const file of readdirSync(resolve(distDir, "scripts"))) {
        if (file.endsWith(".css")) {
            const cssPath = resolve(distDir, "scripts", file);
            const css = readFileSync(cssPath, "utf8").trim();
            if (css) {
                collectedCss.push({ name, css });
            }
            unlinkSync(cssPath); // Remove so next entry doesn't see stale file
        }
    }

    console.log(`✓ Built ${name}`);
}

// --- Step 5: Merge collected CSS → styles/plugin.css ---
// Deduplicate: global.css appears in every entry, keep only first occurrence
const seen = new Set();
const uniqueCssParts = [];

for (const { css } of collectedCss) {
    if (!seen.has(css)) {
        seen.add(css);
        uniqueCssParts.push(css);
    }
}

const mergedCss = uniqueCssParts.join("\n");
writeFileSync(resolve(distDir, "styles", "plugin.css"), mergedCss, "utf8");
console.log(
    `✓ Merged ${collectedCss.length} CSS bundles → styles/plugin.css (${uniqueCssParts.length} unique)`,
);

console.log("\n✅ Build complete → dist/");
